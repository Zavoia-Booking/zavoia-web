const blockStyle = ([x, y, width, height, kind, radius = 0.5, rotate]: AtelierWireBlock, accent: string): CSSProperties => ({
  left: `${(x / 64) * 100}%`,
  top: `${(y / 44) * 100}%`,
  width: `${(width / 64) * 100}%`,
  height: `${(height / 44) * 100}%`,
  background: kind === "s" ? "var(--wire-soft)"
    : kind === "t" ? "var(--wire-ink)"
      : kind === "l" ? "var(--wire-line)"
        : kind === "a" ? accent
          : kind === "i" ? "var(--c-ink)"
            : `color-mix(in oklch, ${accent} 42%, var(--c-canvas))`,
  borderRadius: radius,
  transform: rotate ? `rotate(${rotate}deg)` : undefined,
  filter: kind === "g" ? "blur(3px)" : undefined,
});

/** A static composition guide, using the dashboard's exact variant geometry. */
export function DemoStyleThumbnail({ sectionType, variantId, accent }: {
  sectionType: SectionType;
  variantId: string;
  accent: string;
}) {
  const blocks = STYLE_WIREFRAMES[`${sectionType}:${variantId}`];
  if (!blocks) return null;
  const dark = blocks.some(([,, width, height, kind]) => kind === "i" && width >= 60 && height >= 20);
  return (
    <span className={styles.thumbnail} aria-hidden="true" data-dark={dark || undefined}>
      {blocks.map((block, index) => <i key={index} style={blockStyle(block, accent)} />)}
    </span>
  );
}
